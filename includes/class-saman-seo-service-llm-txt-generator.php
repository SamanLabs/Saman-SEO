<?php
/**
 * Generates the llms.txt file read by some AI tools and LLM services.
 *
 * The file is served at /llms.txt (the path used by the llmstxt.org
 * proposal). The legacy /llm.txt path this plugin used before 301-redirects
 * to it. Google Search does not use llms.txt; it is an optional file for
 * other services only.
 *
 * @package Saman\SEO
 */

namespace Saman\SEO\Service;

defined( 'ABSPATH' ) || exit;

/**
 * LLMs.txt generator.
 */
class LLM_TXT_Generator {

	/**
	 * Query var that routes requests to this service.
	 */
	const QUERY_VAR = 'SAMAN_SEO_llm_txt';

	/**
	 * Primary public path of the file.
	 */
	const PATH = '/llms.txt';

	/**
	 * Legacy path kept working through a permanent redirect.
	 */
	const LEGACY_PATH = '/llm.txt';

	/**
	 * Bump whenever the rewrite rules below change so they are flushed once.
	 */
	const REWRITE_VERSION = '2';

	/**
	 * Option storing the rewrite version that was last flushed.
	 */
	const REWRITE_VERSION_OPTION = 'SAMAN_SEO_llm_txt_rewrite_version';

	/**
	 * Boot hooks.
	 *
	 * @return void
	 */
	public function boot() {
		if ( ! \Saman\SEO\Helpers\module_enabled( 'llm_txt' ) ) {
			return;
		}

		if ( ! saman_seo_apply_filters( 'saman_seo_feature_toggle', true, 'llm_txt' ) ) {
			return;
		}

		add_action( 'init', array( $this, 'register_rewrite_rules' ) );
		add_action( 'init', array( $this, 'maybe_flush_rewrite_rules' ), 99 );
		add_action( 'template_redirect', array( $this, 'render_llm_txt' ), 0 );
	}

	/**
	 * Public URL of the llms.txt file.
	 *
	 * @return string
	 */
	public static function get_url() {
		return home_url( self::PATH );
	}

	/**
	 * Register rewrite rules for /llms.txt and the legacy /llm.txt path.
	 *
	 * @return void
	 */
	public function register_rewrite_rules() {
		add_rewrite_rule( '^llms\.txt$', 'index.php?' . self::QUERY_VAR . '=1', 'top' );
		add_rewrite_rule( '^llm\.txt$', 'index.php?' . self::QUERY_VAR . '=legacy', 'top' );
		add_rewrite_tag( '%' . self::QUERY_VAR . '%', '(1|legacy)' );
	}

	/**
	 * Flush rewrite rules once after the rule set changes.
	 *
	 * Compares a stored version against REWRITE_VERSION so the (expensive)
	 * flush runs a single time after an update, never on every request.
	 *
	 * @return bool True when a flush ran.
	 */
	public function maybe_flush_rewrite_rules() {
		if ( self::REWRITE_VERSION === (string) get_option( self::REWRITE_VERSION_OPTION, '' ) ) {
			return false;
		}

		flush_rewrite_rules( false );
		update_option( self::REWRITE_VERSION_OPTION, self::REWRITE_VERSION, false );

		return true;
	}

	/**
	 * Decide how to answer a request from the query var value.
	 *
	 * @param mixed $query_value Value of the routing query var.
	 * @return string 'serve', 'redirect' or '' (not ours).
	 */
	public static function resolve_request( $query_value ) {
		$query_value = (string) $query_value;

		if ( 'legacy' === $query_value ) {
			return 'redirect';
		}

		if ( '1' === $query_value ) {
			return 'serve';
		}

		return '';
	}

	/**
	 * Render llms.txt, or redirect the legacy /llm.txt path to it.
	 *
	 * @return void
	 */
	public function render_llm_txt() {
		$action = self::resolve_request( get_query_var( self::QUERY_VAR ) );

		if ( '' === $action ) {
			return;
		}

		if ( 'redirect' === $action ) {
			wp_safe_redirect( self::get_url(), 301, 'Saman SEO' );
			exit;
		}

		$content = $this->generate_llm_txt_content();

		nocache_headers();
		header( 'Content-Type: text/plain; charset=UTF-8' );

		echo $content; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped

		exit;
	}

	/**
	 * Generate the llms.txt content.
	 *
	 * @return string
	 */
	private function generate_llm_txt_content() {
		$output = array();

		// Header
		if ( ! function_exists( 'get_plugin_data' ) ) {
			require_once ABSPATH . 'wp-admin/includes/plugin.php';
		}

		$plugin_info    = get_plugin_data( SAMAN_SEO_PATH . 'saman-seo.php', false, false );
		$plugin_version = $plugin_info['Version'] ?? SAMAN_SEO_VERSION;

		// Site title (H1). Per the llms.txt spec (llmstxt.org) the file MUST
		// begin with a single `# Name` H1, so this is emitted first.
		$custom_title = get_option( 'SAMAN_SEO_llm_txt_title', '' );
		$title        = ! empty( $custom_title ) ? $custom_title : get_bloginfo( 'name' );
		$output[]     = '# ' . $title;
		$output[]     = '';

		// Optional one-line summary, emitted as a blockquote per the spec.
		$custom_description = get_option( 'SAMAN_SEO_llm_txt_description', '' );
		$description        = ! empty( $custom_description ) ? $custom_description : get_bloginfo( 'description' );
		if ( $description ) {
			$output[] = '> ' . $description;
			$output[] = '';
		}

		// Provenance note (kept below the H1/summary so the spec-required
		// heading remains the very first line of the document).
		$output[] = sprintf(
			'Generated by %s v%s. This is an llms.txt file: an optional, machine-readable index of the site for AI tools that support it.',
			get_bloginfo( 'name' ),
			$plugin_version
		);
		$output[] = '';

		// Sitemaps section
		$output[] = '## Sitemaps';
		$output[] = '';

		// Add sitemap if enabled
		if ( '1' === get_option( 'SAMAN_SEO_enable_sitemap_enhancer', '0' ) ) {
			$output[] = '- [XML Sitemap](' . home_url( '/sitemap_index.xml' ) . '): Contains all public & indexable URLs for this website.';
		} else {
			// Fallback to WordPress core sitemap
			$output[] = '- [XML Sitemap](' . home_url( '/wp-sitemap.xml' ) . '): Contains all public & indexable URLs for this website.';
		}
		$output[] = '';

		// Get post types
		$post_types = get_post_types(
			array(
				'public'  => true,
				'show_ui' => true,
			),
			'objects'
		);

		unset( $post_types['attachment'] );

		$posts_per_type = absint( get_option( 'SAMAN_SEO_llm_txt_posts_per_type', 50 ) );
		$posts_per_type = max( 1, min( 500, $posts_per_type ) ); // Clamp between 1 and 500

		$include_excerpt = get_option( 'SAMAN_SEO_llm_txt_include_excerpt', '1' );

		// Generate sections for each post type
		foreach ( $post_types as $post_type ) {
			$posts = get_posts(
				array(
					'post_type'      => $post_type->name,
					'posts_per_page' => $posts_per_type,
					'post_status'    => 'publish',
					'orderby'        => 'date',
					'order'          => 'DESC',
				)
			);

			if ( empty( $posts ) ) {
				continue;
			}

			$output[] = '## ' . $post_type->label;
			$output[] = '';

			foreach ( $posts as $post ) {
				$title = get_the_title( $post );
				$url   = get_permalink( $post );

				// Get excerpt or meta description if enabled
				$description = '';
				if ( '1' === $include_excerpt ) {
					$meta_desc = get_post_meta( $post->ID, '_SAMAN_SEO_meta_description', true );

					if ( $meta_desc ) {
						$description = ' - ' . wp_trim_words( $meta_desc, 20, '...' );
					} elseif ( has_excerpt( $post ) ) {
						$description = ' - ' . wp_trim_words( get_the_excerpt( $post ), 20, '...' );
					}
				}

				$output[] = '- [' . esc_html( $title ) . '](' . esc_url( $url ) . ')' . esc_html( $description );
			}

			$output[] = '';
		}

		/**
		 * Filter the generated llm.txt content.
		 *
		 * @param array $output Array of lines to be joined.
		 */
		$output = saman_seo_apply_filters( 'saman_seo_llm_txt_content', $output );

		return implode( "\n", $output );
	}
}
